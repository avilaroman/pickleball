from typing import List, Tuple


def parse_data(data_str: str) -> Tuple[List[int], List[float], List[float], List[float], List[int]]:
    indices: List[int] = []
    xs: List[float] = []
    ys: List[float] = []
    vs: List[float] = []
    bounces: List[int] = []
    for raw_line in data_str.strip().splitlines():
        parts = raw_line.strip().split()
        if len(parts) != 5:
            continue
        idx = int(float(parts[0]))
        x = float(parts[1])
        y = float(parts[2])
        v = float(parts[3])
        bounce = int(float(parts[4]))
        indices.append(idx)
        xs.append(x)
        ys.append(y)
        vs.append(v)
        bounces.append(bounce)
    return indices, xs, ys, vs, bounces


def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


def clamp01(t: float) -> float:
    return 0.0 if t < 0 else 1.0 if t > 1 else t


def viridis_rgb_hex(t: float) -> str:
    # Approximate viridis with 5-stop interpolation
    stops = [
        (68, 1, 84),    # #440154
        (59, 82, 139),  # #3b528b
        (33, 144, 141), # #21908d
        (94, 201, 98),  # #5ec962
        (253, 231, 37), # #fde725
    ]
    t = clamp01(t)
    n = len(stops) - 1
    f = t * n
    i = int(f)
    if i >= n:
        r, g, b = stops[-1]
    else:
        frac = f - i
        r = int(round(lerp(stops[i][0], stops[i+1][0], frac)))
        g = int(round(lerp(stops[i][1], stops[i+1][1], frac)))
        b = int(round(lerp(stops[i][2], stops[i+1][2], frac)))
    return f"#{r:02x}{g:02x}{b:02x}"


def star_points(cx: float, cy: float, r_outer: float, r_inner: float, num_points: int = 5, rotation_deg: float = -90.0) -> str:
    import math

    pts = []
    angle0 = math.radians(rotation_deg)
    step = math.pi / num_points
    for k in range(num_points * 2):
        r = r_outer if k % 2 == 0 else r_inner
        angle = angle0 + k * step
        x = cx + r * math.cos(angle)
        y = cy + r * math.sin(angle)
        pts.append(f"{x:.1f},{y:.1f}")
    return " ".join(pts)


def scale_linear(value: float, src_min: float, src_max: float, dst_min: float, dst_max: float) -> float:
    if src_max == src_min:
        return (dst_min + dst_max) * 0.5
    t = (value - src_min) / (src_max - src_min)
    return dst_min + t * (dst_max - dst_min)


def build_html(indices: List[int], xs: List[float], ys: List[float], vs: List[float], bounces: List[int]) -> str:
    # Layout sizes
    total_w = 1200
    total_h = 650
    margin = 40
    plot_w = 520
    plot_h = 520
    chart_w = 520
    chart_h = 520

    # Convert speeds to km/h (assume input in m/s). If different units, adjust factor.
    SPEED_CONVERSION_TO_KMH = 3.6
    vs_kmh = [v * SPEED_CONVERSION_TO_KMH for v in vs]

    # Data bounds
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    min_v, max_v = min(vs_kmh), max(vs_kmh)
    min_i, max_i = min(indices), max(indices)

    # Areas
    traj_x0 = margin
    traj_y0 = margin
    chart_x0 = margin + plot_w + 80
    chart_y0 = margin

    # Build SVG elements
    svg_elems: List[str] = []

    # Background
    svg_elems.append(f'<rect x="0" y="0" width="{total_w}" height="{total_h}" fill="#ffffff"/>')

    # Titles
    svg_elems.append(f'<text x="{traj_x0}" y="{traj_y0 - 12}" font-family="Arial" font-size="16" fill="#111">Trayectoria de la pelota (color = velocidad km/h)</text>')
    svg_elems.append(f'<text x="{chart_x0}" y="{chart_y0 - 12}" font-family="Arial" font-size="16" fill="#111">Velocidad (km/h) vs. fotograma</text>')

    # Arrowhead definition (adopts stroke color)
    svg_elems.append(
        '<defs>'
        '<marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto">'
        '<path d="M 0 0 L 10 5 L 0 10 z" fill="context-stroke" />'
        '</marker>'
        '</defs>'
    )

    # Borders
    svg_elems.append(f'<rect x="{traj_x0}" y="{traj_y0}" width="{plot_w}" height="{plot_h}" fill="none" stroke="#ccc"/>')
    svg_elems.append(f'<rect x="{chart_x0}" y="{chart_y0}" width="{chart_w}" height="{chart_h}" fill="none" stroke="#ccc"/>')

    # Trajectory segments colored by speed
    for i in range(len(xs) - 1):
        x0 = scale_linear(xs[i], min_x, max_x, traj_x0, traj_x0 + plot_w)
        y0 = scale_linear(ys[i], min_y, max_y, traj_y0, traj_y0 + plot_h)
        x1 = scale_linear(xs[i+1], min_x, max_x, traj_x0, traj_x0 + plot_w)
        y1 = scale_linear(ys[i+1], min_y, max_y, traj_y0, traj_y0 + plot_h)
        v_mid = (vs_kmh[i] + vs_kmh[i+1]) * 0.5
        t = 0.0 if max_v == min_v else (v_mid - min_v) / (max_v - min_v)
        color = viridis_rgb_hex(t)
        svg_elems.append(f'<line x1="{x0:.1f}" y1="{y0:.1f}" x2="{x1:.1f}" y2="{y1:.1f}" stroke="{color}" stroke-width="2" stroke-linecap="round"/>')

    # Trajectory points
    for i in range(len(xs)):
        px = scale_linear(xs[i], min_x, max_x, traj_x0, traj_x0 + plot_w)
        py = scale_linear(ys[i], min_y, max_y, traj_y0, traj_y0 + plot_h)
        t = 0.0 if max_v == min_v else (vs_kmh[i] - min_v) / (max_v - min_v)
        color = viridis_rgb_hex(t)
        svg_elems.append(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="2.5" fill="{color}" />')

    # Velocity vectors on trajectory (direction from position deltas, length scaled by km/h)
    def map_to_svg(xd: float, yd: float) -> Tuple[float, float]:
        return (
            scale_linear(xd, min_x, max_x, traj_x0, traj_x0 + plot_w),
            scale_linear(yd, min_y, max_y, traj_y0, traj_y0 + plot_h),
        )

    def normalize(dx_p: float, dy_p: float) -> Tuple[float, float]:
        mag = (dx_p * dx_p + dy_p * dy_p) ** 0.5
        if mag == 0:
            return 0.0, 0.0
        return dx_p / mag, dy_p / mag

    L_MIN = 6.0
    L_MAX = 22.0
    n = len(xs)
    for i in range(n):
        # central difference for direction
        if i == 0:
            dx = xs[i+1] - xs[i]
            dy = ys[i+1] - ys[i]
        elif i == n - 1:
            dx = xs[i] - xs[i-1]
            dy = ys[i] - ys[i-1]
        else:
            dx = (xs[i+1] - xs[i-1]) * 0.5
            dy = (ys[i+1] - ys[i-1]) * 0.5

        # map to pixel space for accurate orientation under non-uniform scaling
        px, py = map_to_svg(xs[i], ys[i])
        p_dir_x, p_dir_y = map_to_svg(xs[i] + dx, ys[i] + dy)
        dir_px = p_dir_x - px
        dir_py = p_dir_y - py
        ux, uy = normalize(dir_px, dir_py)

        # scale length by speed in km/h
        vk = vs_kmh[i]
        t = 0.0 if max_v == min_v else (vk - min_v) / (max_v - min_v)
        length = L_MIN + t * (L_MAX - L_MIN)

        ex = px + ux * length
        ey = py + uy * length
        color = viridis_rgb_hex(t)
        svg_elems.append(f'<line x1="{px:.1f}" y1="{py:.1f}" x2="{ex:.1f}" y2="{ey:.1f}" stroke="{color}" stroke-width="2" marker-end="url(#arrow)"/>')

    # Bounce markers on trajectory
    for i in range(len(xs)):
        if bounces[i] == 1:
            px = scale_linear(xs[i], min_x, max_x, traj_x0, traj_x0 + plot_w)
            py = scale_linear(ys[i], min_y, max_y, traj_y0, traj_y0 + plot_h)
            pts = star_points(px, py, 10.0, 5.0, num_points=5)
            svg_elems.append(f'<polygon points="{pts}" fill="#e63946" stroke="#111" stroke-width="0.8"/>')
            svg_elems.append(f'<text x="{px + 12:.1f}" y="{py - 6:.1f}" font-family="Arial" font-size="11" fill="#e63946">{indices[i]}</text>')

    # Colorbar (vertical) for speed
    cb_x = traj_x0 + plot_w + 20
    cb_y = traj_y0
    cb_w = 18
    cb_h = plot_h
    steps = 50
    for s in range(steps):
        t = s / (steps - 1)
        y = cb_y + (1 - t) * cb_h
        color = viridis_rgb_hex(t)
        svg_elems.append(f'<rect x="{cb_x}" y="{y:.2f}" width="{cb_w}" height="{cb_h/steps + 1:.2f}" fill="{color}" stroke="none"/>')
    svg_elems.append(f'<rect x="{cb_x}" y="{cb_y}" width="{cb_w}" height="{cb_h}" fill="none" stroke="#666"/>')
    svg_elems.append(f'<text x="{cb_x + cb_w + 6}" y="{cb_y + 12}" font-family="Arial" font-size="11" fill="#111">{max_v:.1f} km/h</text>')
    svg_elems.append(f'<text x="{cb_x + cb_w + 6}" y="{cb_y + cb_h}" font-family="Arial" font-size="11" fill="#111">{min_v:.1f} km/h</text>')
    svg_elems.append(f'<text x="{cb_x - 4}" y="{cb_y - 8}" font-family="Arial" font-size="12" fill="#111">Velocidad (km/h)</text>')

    # Speed over frames polyline
    # Axes box already drawn. Build polyline points
    poly_pts: List[str] = []
    for i in range(len(indices)):
        tx = scale_linear(indices[i], min_i, max_i, chart_x0, chart_x0 + chart_w)
        # invert so higher speed is visually higher (SVG y increases down)
        ty = scale_linear(vs_kmh[i], min_v, max_v, chart_y0 + chart_h, chart_y0)
        poly_pts.append(f"{tx:.1f},{ty:.1f}")
    svg_elems.append(f'<polyline points="{' '.join(poly_pts)}" fill="none" stroke="#1f77b4" stroke-width="2"/>')

    # Bounce markers on chart
    for i in range(len(indices)):
        if bounces[i] == 1:
            tx = scale_linear(indices[i], min_i, max_i, chart_x0, chart_x0 + chart_w)
            ty = scale_linear(vs[i], min_v, max_v, chart_y0 + chart_h, chart_y0)
            pts = star_points(tx, ty, 9.0, 4.5, num_points=5)
            svg_elems.append(f'<polygon points="{pts}" fill="#e63946" stroke="#111" stroke-width="0.8"/>')
            svg_elems.append(f'<text x="{tx + 10:.1f}" y="{ty - 6:.1f}" font-family="Arial" font-size="11" fill="#e63946">{indices[i]}</text>')

    # Legend
    legend_x = chart_x0
    legend_y = chart_y0 + chart_h + 30
    star = star_points(legend_x + 10, legend_y - 6, 8.0, 4.0)
    svg_elems.append(f'<polygon points="{star}" fill="#e63946" stroke="#111" stroke-width="0.8"/>')
    svg_elems.append(f'<text x="{legend_x + 28}" y="{legend_y - 2}" font-family="Arial" font-size="12" fill="#111">Bounce</text>')

    svg = f"""
<!DOCTYPE html>
<html lang=\"es\">
<head>
  <meta charset=\"utf-8\" />
  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />
  <title>Gráficos de pickleball</title>
  <style>
    body {{ background:#fafafa; margin: 10px; font-family: Arial, sans-serif; }}
    .container {{ width: {total_w}px; }}
  </style>
  </head>
  <body>
    <div class=\"container\">
      <svg width=\"{total_w}\" height=\"{total_h}\" viewBox=\"0 0 {total_w} {total_h}\" xmlns=\"http://www.w3.org/2000/svg\">
        {''.join(svg_elems)}
      </svg>
    </div>
  </body>
</html>
"""
    return svg


def main() -> None:
    indices, xs, ys, vs, bounces = parse_data(DATA_STR)
    html = build_html(indices, xs, ys, vs, bounces)
    output_path = "/workspace/pickleball_plots.html"
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"Archivo HTML creado en: {output_path}")


if __name__ == "__main__":
    main()

